BT = os.path.join(D.ROOT, "outputs", "backtest")
pct = lambda x: 100 * (np.exp(x) - 1)

def _tbl(df):
    df = df.copy(); cols = list(df.columns)
    out = ["| " + " | ".join(cols) + " |", "|" + "|".join("---" for _ in cols) + "|"]
    for r in df.itertuples(index=False):
        out.append("| " + " | ".join(f"{v:.3f}" if isinstance(v, float) else str(v) for v in r) + " |")
    return "\n".join(out)

def loo_coverage(e, level=0.90):
    """Leave-one-out: is each error inside the t-interval built from the other errors?"""
    e = np.asarray(e); hits = []
    for i in range(len(e)):
        o = np.delete(e, i)
        if len(o) >= 3: hits.append(abs(e[i]) <= stats.t.ppf(0.5 + level / 2, len(o) - 1) * np.sqrt((o ** 2).mean()))
    return hits

def write_report():
    c = D.cfg(); sel = json.load(open(f"{BT}/selection.json")); _, names = D.roles_names()
    bm = pd.read_csv(f"{BT}/monthly_errors.csv", dtype={"unit": str}); bd = pd.read_csv(f"{BT}/daily_errors.csv", dtype={"unit": str})
    rm = pd.read_csv(f"{BT}/unit_rmse.csv", dtype={"unit": str})
    L = ["# Backtest report", "", "Generated by `python -m halo.report` from `outputs/backtest/`. All errors are in log points (0.10 is about 10%).", ""]
    L += ["## What was selected", ""]
    rows = []
    for typ in ("raw", "adjusted"):
        rows.append((typ, sel["monthly"][typ], sel["daily"][typ]))
    L += [_tbl(pd.DataFrame(rows, columns=["target", "monthly model (December)", "daily model (launch fortnight)"])), ""]
    L += ["Rule (pre-registered): the simplest model wins unless a more complex one has at least 5% lower error. `nn` is the pooled neural model.", ""]
    for typ in ("raw", "adjusted"):
        t = sel["tables"][typ]
        L += [f"## {typ.capitalize()} target, GTA V", "", "Monthly, two months ahead:", ""]
        d = pd.DataFrame({"model": list(t["monthly_mae_h2_all_origins"]), "MAE, all origins": list(t["monthly_mae_h2_all_origins"].values())})
        d["RMSE, Oct to Dec only"] = d.model.map(t["monthly_rmse_oct_to_dec"]); d["selected"] = np.where(d.model == sel["monthly"][typ], "yes", "")
        n_all = bm[(bm.type == typ) & (bm.unit == D.TARGET) & (bm.h == 2) & (bm.model == "clim")].err.notna().sum()
        n_dec = bm[(bm.type == typ) & (bm.unit == D.TARGET) & (bm.h == 2) & (bm.model == "clim") & bm.origin.str.endswith("-10")].err.notna().sum()
        L += [_tbl(d.sort_values("MAE, all origins")), "", f"Origins: {n_all} monthly origins (2017-10 to 2026-08); {n_dec} of them are October to December.", "", "Daily, mean of days 4 to 17 ahead:", ""]
        d = pd.DataFrame({"model": list(t["daily_mae_window"]), "MAE of 14-day mean": list(t["daily_mae_window"].values())})
        d["eligible"] = np.where(d.model == "sarimax_trends", "no (uses Trends)", "yes"); d["selected"] = np.where(d.model == sel["daily"][typ], "yes", "")
        L += [_tbl(d.sort_values("MAE of 14-day mean")), "", "Origins: 30 daily origins (2026-09-30 to 2026-10-29). They overlap heavily; treat this as about three independent tests.", ""]
        # December detail
        g = bm[(bm.type == typ) & (bm.unit == D.TARGET) & (bm.h == 2) & (bm.model == sel["monthly"][typ]) & bm.origin.str.endswith("-10")].dropna()
        wm = D.load_monthly(c); s = D.build_targets(wm, c)[typ][D.TARGET]
        base = g.origin.map(lambda o: float(s.loc[pd.Period(o, "M")]))
        dd = pd.DataFrame({"year": g.origin.str[:4].values, "forecast Oct to Dec, %": pct(g.fc.values - base.values), "actual Oct to Dec, %": pct(g.actual.values - base.values), "error, log": g.err.values})
        L += [f"December backtests of the selected monthly model (`{sel['monthly'][typ]}`):", "", _tbl(dd), ""]
    # intervals, power, calibration
    L += ["## Interval width and what it can detect", ""]
    rows = []
    for typ in ("raw", "adjusted"):
        r = rm[(rm.type == typ) & (rm.unit == D.TARGET)].iloc[0]
        k2 = stats.t.ppf(0.95, int(r.n_o2) - 1) * r.rmse_o2; k1 = stats.t.ppf(0.95, 2) * r.rmse_o1
        rows.append((typ, "O1 launch fortnight", r.rmse_o1, 2, f"-{-pct(-k1):.0f}% / +{pct(k1):.0f}%"))
        rows.append((typ, "O2 December", r.rmse_o2, int(r.n_o2) - 1, f"-{-pct(-k2):.0f}% / +{pct(k2):.0f}%"))
    L += [_tbl(pd.DataFrame(rows, columns=["target", "outcome", "backtest RMSE", "t df", "90% interval = smallest detectable effect"])), ""]
    L += ["An effect smaller than these ranges cannot be told apart from ordinary forecast error.", "", "## Calibration checks", ""]
    rows = []
    for typ in ("raw", "adjusted"):
        m = bm[(bm.type == typ) & (bm.model == sel["monthly"][typ]) & (bm.h == 2) & bm.origin.str.endswith("-10")].dropna()
        hits = [h for u in m.unit.unique() if u != D.SIBLING for h in loo_coverage(m[m.unit == u].err.values)]
        hg = loo_coverage(m[m.unit == D.TARGET].err.values)
        rows.append((typ, "O2: 90% interval, leave-one-out", f"{np.mean(hg):.0%} of {len(hg)} (GTA V)", f"{np.mean(hits):.0%} of {len(hits)} (all 19 units)"))
        w = window_errors(bd[(bd.type == typ) & (bd.model == sel["daily"][typ])], c); last = w[w.origin == c["daily"]["bt_last"]]
        ins = [abs(float(last[last.unit == u].err.iloc[0])) <= stats.t.ppf(0.95, 2) * float(rm[(rm.type == typ) & (rm.unit == u)].rmse_o1.iloc[0]) for u in last.unit.unique() if u != D.SIBLING]
        rows.append((typ, "O1: 90% interval at the last origin (in-sample, optimistic)", "", f"{np.mean(ins):.0%} of {len(ins)} units"))
    L += [_tbl(pd.DataFrame(rows, columns=["target", "check", "GTA V", "panel"])), "",
          "The O1 check reuses the errors that set the interval, and its df = 2 makes the interval deliberately wide. No backtest window contains Thanksgiving, so O1 may still be too narrow for that week.", ""]
    # does adjustment help
    r0 = rm[(rm.unit == D.TARGET)].set_index("type")
    L += ["## Does the control adjustment help?", "",
          f"- December (O2) RMSE: raw {r0.loc['raw', 'rmse_o2']:.3f}, adjusted {r0.loc['adjusted', 'rmse_o2']:.3f}.",
          f"- Launch fortnight (O1) RMSE: raw {r0.loc['raw', 'rmse_o1']:.3f}, adjusted {r0.loc['adjusted', 'rmse_o1']:.3f}.",
          "- Read these two lines directly: the adjustment helps where its RMSE is lower and does not where it is higher. GTA V's December rise is largely its own (GTA Online December updates), not Steam-wide, so dividing by the control index cannot remove it. The adjustment is kept as primary for what it protects against, Steam-wide shocks during the test window.", ""]
    L += ["## Leakage tests", ""] + [f"- {'PASS' if t['passed'] else 'FAIL'}: {t['check']}" for t in sel["leakage_tests"]] + [""]
    L += ["Also enforced in code: every backtest fit asserts its newest training point is at or before the origin; the freeze asserts the inputs end exactly at the freeze origin; a unit is never part of its own control index; neural inputs are normalized using only the input window.", ""]
    L += ["## Limits", "",
          "- 88 daily points per series. The daily neural model is trained on 19 series pooled, 14 lags, and can only be tested 17 days ahead on Sep 30 to Nov 15. It has never seen a holiday.",
          "- Neural hyperparameters were fixed in advance and not tuned. A tuned model might do better; this data cannot show that honestly.",
          "- Where the neural model was selected, it won on all monthly origins. Check the December-only column: if climatology is better there, that is why a climatology sensitivity result is frozen alongside (pre-registration, amendment 2).",
          "- Selection used all monthly origins, not only December. The December column shows how each model did on the month that matters.", ""]
    open(os.path.join(D.ROOT, "docs", "BACKTEST_REPORT.md"), "w").write("\n".join(L))
    print("wrote docs/BACKTEST_REPORT.md")

def export_dashboard(version="v1"):
    """CSV files the dashboard reads. Re-run after `halo.track` and replace the files in the dashboard's Sources."""
    c = D.cfg(); out = os.path.join(D.ROOT, "outputs", "dashboard"); os.makedirs(out, exist_ok=True)
    fr = os.path.join(D.ROOT, "outputs", "frozen", version); roles, names = D.roles_names(); fz = c["freeze"]
    dly = pd.read_csv(os.path.join(D.ROOT, "data", "steam_gtav_daily_peak.csv"))
    dly[["date", "legacy_peak", "enhanced_peak", "combined_peak_sum", "partial_day"]].rename(columns={"combined_peak_sum": "combined_peak"}).to_csv(f"{out}/players_daily.csv", index=False)
    mon = pd.read_csv(os.path.join(D.ROOT, "data", "gtav_monthly_combined.csv")); mon["month"] = mon.month + "-01"
    mon[["month", "legacy_avg", "enhanced_avg", "combined_avg"]].to_csv(f"{out}/players_monthly.csv", index=False)
    ev = pd.read_csv(os.path.join(D.ROOT, "data", "gta_events.csv"))
    grp = {"leak": "leak", "leak_followup": "leak", "steam_sale": "steam"}
    ev["group"] = [grp.get(t, "gta5" if s == "gta5" else "gta6") for t, s in zip(ev.event_type, ev.subject)]
    ev = ev[["date", "end_date", "group", "event_type", "title", "confidence"]].astype(object).where(ev.notna(), None)
    json.dump(ev.to_dict("records"), open(f"{out}/events.json", "w"), indent=0)          # JSON: titles contain commas and quotes
    tr = pd.read_csv(os.path.join(D.ROOT, "data", "trends_daily_2026-03_to_2026-11.csv")); tr.to_csv(f"{out}/trends.csv", index=False)
    # frozen forecast, GTA V, on readable scales
    fd = pd.read_csv(f"{fr}/frozen_daily.csv", dtype={"unit": str}); fo = pd.read_csv(f"{fr}/frozen_outcomes.csv", dtype={"unit": str})
    wd = D.load_daily(c, with_post=True); td = D.build_targets(wd, c); wm = D.load_monthly(c, with_post=True); tm = D.build_targets(wm, c)
    ref = td["adjusted"][D.TARGET].loc[:fz["daily_origin"]].iloc[-28:].mean()                     # adjusted index: last 28 pre-freeze days = 100
    g = fd[fd.unit == D.TARGET]; r, a = g[g.type == "raw"].set_index("date"), g[g.type == "adjusted"].set_index("date")
    f = pd.DataFrame({"date": r.index, "forecast": np.exp(r.forecast_log).round(0), "lo80": np.exp(r.lo80).round(0), "hi80": np.exp(r.hi80).round(0), "lo95": np.exp(r.lo95).round(0), "hi95": np.exp(r.hi95).round(0),
                      "adj_forecast": (100 * np.exp(a.forecast_log - ref)).round(2).values, "adj_lo80": (100 * np.exp(a.lo80 - ref)).round(2).values, "adj_hi80": (100 * np.exp(a.hi80 - ref)).round(2).values,
                      "adj_lo95": (100 * np.exp(a.lo95 - ref)).round(2).values, "adj_hi95": (100 * np.exp(a.hi95 - ref)).round(2).values, "basis": r.source.values})
    f.to_csv(f"{out}/forecast.csv", index=False)
    # adjusted history for the chart
    ah = td["adjusted"][D.TARGET].loc[:fz["daily_origin"]]
    pd.DataFrame({"date": ah.index.strftime("%Y-%m-%d"), "adj_index": (100 * np.exp(ah.values - ref)).round(2)}).to_csv(f"{out}/adjusted_history.csv", index=False)
    # tracker: every day after the freeze origin that has data (partial days shown, not scored)
    raw_all = pd.read_csv(os.path.join(D.ROOT, "data", "panel_daily_peak.csv"), dtype={"app_id": str})
    pp = os.path.join(D.ROOT, "data", "post", "panel_daily_peak_post.csv")
    if os.path.exists(pp): raw_all = pd.concat([raw_all, pd.read_csv(pp, dtype={"app_id": str})])
    t = raw_all[(raw_all.app_id == D.TARGET) & (raw_all.date > fz["daily_origin"])].drop_duplicates("date").sort_values("date")
    rows = []; cum = cum_a = 0.0; n = 0
    for x in t.itertuples():
        phase = "pre-launch" if x.date < fz["launch"] else "fortnight" if x.date <= fz["o1_end"] else "december"
        row = dict(date=x.date, partial_day=int(x.partial_day), actual=int(x.peak_players), phase=phase)
        if x.date in r.index:
            row["forecast"] = round(float(np.exp(r.forecast_log[x.date])))
            if not x.partial_day:
                gl = np.log(x.peak_players) - r.forecast_log[x.date]; ga = td["adjusted"][D.TARGET].loc[pd.Timestamp(x.date)] - a.forecast_log[x.date]
                row.update(gap_pct=round(pct(gl), 2), adj_actual=round(float(100 * np.exp(td["adjusted"][D.TARGET].loc[pd.Timestamp(x.date)] - ref)), 2), adj_forecast=round(float(100 * np.exp(a.forecast_log[x.date] - ref)), 2), adj_gap_pct=round(pct(ga), 2))
                if phase == "fortnight":                      # December days are shown but only judged as a full month (O2)
                    n += 1; cum += gl; cum_a += ga
                    row.update(days_scored=n, mean_gap_pct=round(pct(cum / n), 2), adj_mean_gap_pct=round(pct(cum_a / n), 2))
        rows.append(row)
    cols = ["date", "phase", "partial_day", "actual", "forecast", "gap_pct", "adj_actual", "adj_forecast", "adj_gap_pct", "days_scored", "mean_gap_pct", "adj_mean_gap_pct"]
    tk = pd.DataFrame(rows).reindex(columns=cols)
    tk["cum_gap_player_days"] = ((tk.actual - tk.forecast).where((tk.phase == "fortnight") & (tk.partial_day == 0))).cumsum().round(0)
    tk.to_csv(f"{out}/tracker.csv", index=False)
    # outcomes: frozen forecast + (after launch) actuals and verdicts
    evp = os.path.join(D.ROOT, "outputs", "tracker", "outcomes_eval.csv")
    evd = pd.read_csv(evp, dtype={"unit": str}) if os.path.exists(evp) else None
    rows = []
    for x in fo.itertuples():
        k = x.hi90 - x.point
        if x.type == "raw": fc, lo, hi = np.exp(x.point), np.exp(x.lo90), np.exp(x.hi90)
        else:
            b = ref if x.outcome == "O1" else x.base_oct                                         # adjusted: O1 vs pre-launch = 100, O2 vs October = 100
            fc, lo, hi = 100 * np.exp(x.point - b), 100 * np.exp(x.lo90 - b), 100 * np.exp(x.hi90 - b)
        row = dict(key=f"{x.unit}|{x.type}|{x.outcome}", unit=x.unit, name=names[x.unit], role=roles[x.unit], target=x.type, outcome=x.outcome, model=x.model, forecast=round(fc, 1), lo90=round(lo, 1), hi90=round(hi, 1),
                   detectable_down_pct=round(pct(-k), 1), detectable_up_pct=round(pct(k), 1), n_backtest=x.n_backtest)
        if evd is not None:
            e = evd[(evd.unit == x.unit) & (evd.type == x.type) & (evd.outcome == x.outcome)].iloc[0]
            if np.isfinite(e.actual):
                row.update(gap_pct=round(e.gap_pct, 2), z=round(e.z, 3), verdict=e.get("verdict") if isinstance(e.get("verdict"), str) else "", placebo_rank=e.get("placebo_rank"), placebo_n=e.get("placebo_n"))
        rows.append(row)
    pd.DataFrame(rows).reindex(columns=["key", "unit", "name", "role", "target", "outcome", "model", "forecast", "lo90", "hi90", "detectable_down_pct", "detectable_up_pct", "n_backtest", "gap_pct", "z", "verdict", "placebo_rank", "placebo_n"]).to_csv(f"{out}/outcomes.csv", index=False)
    # backtest tables
    sel = json.load(open(f"{BT}/selection.json")); rows = []
    for typ in ("raw", "adjusted"):
        t_ = sel["tables"][typ]
        for mname, v in t_["monthly_mae_h2_all_origins"].items():
            rows.append(dict(key=f"monthly|{typ}|{mname}", resolution="monthly", target=typ, model=mname, mae_pct=round(pct(v), 1), dec_rmse_pct=round(pct(t_["monthly_rmse_oct_to_dec"].get(mname, np.nan)), 1), selected="yes" if sel["monthly"][typ] == mname else "", eligible="yes"))
        for mname, v in t_["daily_mae_window"].items():
            rows.append(dict(key=f"daily|{typ}|{mname}", resolution="daily", target=typ, model=mname, mae_pct=round(pct(v), 1), dec_rmse_pct=None, selected="yes" if sel["daily"][typ] == mname else "", eligible="no" if mname == "sarimax_trends" else "yes"))
    pd.DataFrame(rows).to_csv(f"{out}/backtest.csv", index=False)
    bm = pd.read_csv(f"{BT}/monthly_errors.csv", dtype={"unit": str}); rows = []
    for typ in ("raw", "adjusted"):
        g = bm[(bm.type == typ) & (bm.unit == D.TARGET) & (bm.h == 2) & (bm.model == sel["monthly"][typ]) & bm.origin.str.endswith("-10")].dropna()
        s = tm[typ][D.TARGET]
        for x in g.itertuples():
            b = float(s.loc[pd.Period(x.origin, "M")]); rows.append(dict(key=f"{typ}|{x.origin[:4]}", target=typ, year=int(x.origin[:4]), forecast_pct=round(pct(x.fc - b), 1), actual_pct=round(pct(x.actual - b), 1)))
        x = fo[(fo.unit == D.TARGET) & (fo.type == typ) & (fo.outcome == "O2")].iloc[0]
        rows.append(dict(key=f"{typ}|2026", target=typ, year=2026, forecast_pct=round(pct(x.point - x.base_oct), 1), actual_pct=None))
    pd.DataFrame(rows).to_csv(f"{out}/backtest_december.csv", index=False)
    print("wrote", out)

if __name__ == "__main__":
    write_report(); export_dashboard()
